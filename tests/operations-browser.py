"""Full local demo: landing -> locked checkout -> paid report -> support -> admin -> refund."""
import os,uuid
from playwright.sync_api import sync_playwright,expect
base=os.environ.get('SAJU_OPERATIONS_URL','http://127.0.0.1:3110')
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 context=b.new_context(viewport={'width':1440,'height':1000})
 errors=[]
 context.on('page',lambda page:page.on('pageerror',lambda e:errors.append(str(e))))
 page=context.new_page()
 page.goto(base+'/index.html?utm_source=instagram&utm_campaign=review')
 page.locator('#name').fill('운영확인')
 page.locator('#birth').fill('2005-12-23')
 page.get_by_role('button',name='나의 사주 풀이 보기').click()
 page.locator('#premium-from-result').click()
 expect(page.locator('#buyer-date')).to_have_value('2005-12-23')
 assert page.locator('.locked-outline li').count()==15
 email='review-'+uuid.uuid4().hex[:8]+'@example.com'
 page.locator('#buyer-email').fill(email)
 for name in ['agreeTerms','agreePrivacy','agreeProduction']:page.locator('[name='+name+']').check()
 page.locator('#pay-button').click()
 expect(page.locator('#open-report')).to_be_visible(timeout=25000)
 page.locator('#open-report').click()
 expect(page.locator('.web-chapter')).to_have_count(15)
 page.locator('.web-chapter').nth(2).locator('summary').click()
 expect(page.locator('.web-chapter').nth(2)).to_contain_text('사주 명식')
 page.locator('#close-web-report').click()
 page.locator('.customer-support summary').click()
 page.locator('#support-message').fill('메일 수신을 확인하고 싶습니다.')
 page.locator('#support-form button').click()
 expect(page.locator('#support-status')).to_contain_text('문의를 접수')
 admin=context.new_page();admin.goto(base+'/admin.html')
 assert admin.request.get(base+'/api/config').json()['demo'] is True
 expect(admin.locator('#login-note')).not_to_contain_text('연결하고 있습니다')
 if admin.locator('#account-setup').is_visible():
  admin.locator('#setup-username').fill('browser_test_admin')
  admin.locator('#setup-password').fill('Only-for-browser-test-2026')
  admin.locator('#setup-password-confirm').fill('Only-for-browser-test-2026')
  admin.locator('#setup-button').click()
 else:
  expect(admin.locator('#login-button')).to_be_enabled()
  admin.locator('#admin-username').fill('browser_test_admin')
  admin.locator('#admin-password').fill('Only-for-browser-test-2026')
  admin.locator('#login-button').click()
 expect(admin.locator('#dashboard')).to_be_visible()
 admin.locator('#order-search').fill(email)
 row=admin.locator('#order-list tr').filter(has_text=email)
 row.get_by_role('button',name='상세 보기').click()
 ticket=admin.locator('.ticket').filter(has_text='메일 수신을 확인하고 싶습니다.')
 ticket.locator('textarea').fill('스팸함을 확인해 주세요. 주문 화면에서 PDF도 받을 수 있습니다.')
 ticket.get_by_role('button',name='답변 저장').click()
 expect(ticket).to_contain_text('운영자 답변')
 page.locator('#refresh-tickets').click()
 expect(page.locator('#customer-tickets')).to_contain_text('스팸함을 확인')
 admin.locator('#close-detail').click()
 for name,value in [('monthly','1000'),('ads','2000'),('feePercent','3'),('perReport','500')]:admin.locator('[name='+name+']').fill(value)
 admin.locator('#cost-form button').click()
 expect(admin.locator('#profit-result')).to_contain_text('예상 수익')
 admin.locator('#campaign-name').fill('first_story')
 admin.locator('#campaign-form button').click()
 assert 'utm_campaign=first_story' in admin.locator('#campaign-result').input_value()
 admin.screenshot(path='/tmp/sajumoon-admin-overview.png',full_page=True)
 admin.set_viewport_size({'width':375,'height':812})
 assert admin.evaluate('document.documentElement.scrollWidth<=innerWidth')
 admin.screenshot(path='/tmp/sajumoon-admin-mobile.png',full_page=True)
 page.locator('#refund-reason').fill('구매 내용을 다시 검토하고 싶습니다.')
 page.locator('#refund-form button').click()
 expect(page.locator('#order-status')).to_contain_text('환불 검토')
 admin.set_viewport_size({'width':1440,'height':1000})
 admin.locator('#refresh-admin').click()
 admin.locator('#order-search').fill(email)
 admin.locator('#order-list tr').filter(has_text=email).get_by_role('button',name='상세 보기').click()
 admin.locator('#action-reason').fill('고객 요청을 확인하여 모의 환불 처리')
 admin.once('dialog',lambda d:d.accept())
 admin.get_by_role('button',name='19,000원 모의 환불').click()
 expect(admin.locator('#detail-info')).to_contain_text('환불 완료')
 page.locator('#check-order').click()
 expect(page.locator('#order-status')).to_contain_text('전액 환불')
 expect(page.locator('#open-report')).to_be_hidden()
 expect(page.locator('#download-report')).to_be_hidden()
 assert not errors,errors
 print('PASS: anonymous attribution, free -> purchase prefill, 15-chapter lock/unlock, web report, support and admin reply, cost model, UTM builder, mobile admin, mock refund and access revocation; no real charge/mail')
 b.close()
